function _wsrWithTimeout(promise, timeoutMs, message) {
  let timer = null;
  return Promise.race([
    promise,
    new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(message || 'Request timed out')), Math.max(1000, Number(timeoutMs || 25000)));
    }),
  ]).finally(() => {
    if (timer) clearTimeout(timer);
  });
}

