function renderWsrTemplate(tpl, ctx) {
  return String(tpl || '').replace(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g, (m, key) => {
    return Object.prototype.hasOwnProperty.call(ctx, key) ? String(ctx[key]) : m;
  });
}

function buildWsrMarkdown(summary, opts) {
  // opts: { days, windowStart?: Date, windowEnd?: Date, weekRef?: Date, titleOverride?: string }
  if (typeof opts === 'number') opts = { days: opts };
  opts = opts || {};
  const end = opts.windowEnd ? new Date(opts.windowEnd) : new Date();
  const days = Math.max(1, Number(opts.days || 7));
  const start = opts.windowStart ? new Date(opts.windowStart) : new Date(end.getTime() - days * 24 * 3600 * 1000);
  const events = summary?.activities || summary?.recent_events || summary?.events || [];
  const { filtered, byProject, byType, byStatus } = _wsrSummarizeEvents(events, start.getTime(), end.getTime());
  const projTotal = summary?.project_total ?? byProject.size;
  const projectEntries = _wsrProjectEntries(byProject);
  const primaryProjectName = projectEntries.length ? String(projectEntries[0][0]) : '(none)';
  const projectNames = _wsrProjectNamesText(byProject);
  const projectTags = _wsrProjectTagsText(byProject);
  const highlights = filtered.slice(0, 10).map(e => _wsrFormatHighlight(e)).join('\n') || '- _(no activity in window)_';

  const wkRef = opts.weekRef ? new Date(opts.weekRef) : end;
  const wk = _wsrIsoWeek(wkRef);
  const title = opts.titleOverride || `Week ${wk.week}, ${wk.year}`;
  const ctx = {
    title,
    week: String(wk.week),
    week_year: String(wk.year),
    week_label: `Week ${wk.week}, ${wk.year}`,
    window_start: _wsrFormatDate(start),
    window_end: _wsrFormatWindowEndInclusive(end),
    generated_at: new Date().toISOString(),
    days: String(days),
    total_events: String(filtered.length),
    active_projects: String(byProject.size),
    total_projects: String(projTotal),
    project_name: primaryProjectName,
    project_names: projectNames,
    project_tags: projectTags,
    project_name_tags: projectTags,
    event_types_count: String(byType.size),
    highlights,
    by_project: _wsrMapToBullets(byProject),
    by_type: _wsrMapToBullets(byType),
    by_status: _wsrMapToBullets(byStatus),
  };
  const tpl = (document.getElementById('wsr-template')?.value) || getWsrTemplate();
  return renderWsrTemplate(tpl, ctx);
}

function _wsrIsoWeek(d) {
  // ISO 8601 week number (week starts Monday; week 1 contains the first Thursday).
  const t = new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()));
  const day = t.getUTCDay() || 7;
  t.setUTCDate(t.getUTCDate() + 4 - day);
  const yearStart = new Date(Date.UTC(t.getUTCFullYear(), 0, 1));
  const week = Math.ceil(((t - yearStart) / 86400000 + 1) / 7);
  return { year: t.getUTCFullYear(), week };
}

