function _wsrBuildWeeklyHistoryEntries(summary, rangeDays, anchorEnd, stamp) {
  const dayMs = 86400000;
  const weekMs = 7 * dayMs;
  const end = anchorEnd ? _wsrStartOfDay(anchorEnd) : _wsrStartOfThuWeek(new Date());
  const rangeStart = new Date(end.getTime() - Math.max(1, Number(rangeDays || 7)) * dayMs);
  const events = summary?.activities || summary?.recent_events || summary?.events || [];
  const entries = [];
  let windowEnd = new Date(end);

  while (windowEnd > rangeStart) {
    const windowStart = new Date(Math.max(rangeStart.getTime(), windowEnd.getTime() - weekMs));
    const prevEnd = new Date(windowStart);
    const prevStart = new Date(prevEnd.getTime() - weekMs);
    const actualDays = Math.max(1, Math.ceil((windowEnd.getTime() - windowStart.getTime()) / dayMs));
    const weekRef = new Date(windowEnd.getTime() - 1);
    const totalEvents = _wsrSummarizeEvents(events, windowStart.getTime(), windowEnd.getTime()).filtered.length;

    entries.push({
      md: buildWsrMarkdown(summary, { days: actualDays, windowStart, windowEnd, weekRef }),
      mdPrev: buildWsrMarkdown(summary, {
        days: 7,
        windowStart: prevStart,
        windowEnd: prevEnd,
        weekRef: new Date(prevEnd.getTime() - 1),
      }),
      stamp,
      days: actualDays,
      totalEvents,
      dataStatusVersion: 2,
      title: `Week ${_wsrIsoWeek(weekRef).week}, ${_wsrIsoWeek(weekRef).year}`,
      windowStart: _wsrFormatDate(windowStart),
      windowEnd: _wsrFormatDate(windowEnd),
    });

    windowEnd = windowStart;
  }

  return entries;
}

async function generateWorkReport() {
  if (_wsrGenerating) {
    setWsrStatus('Generating…');
    return;
  }
  _wsrGenerating = true;
  showWsrBusy('Loading data...');
  const rangeEl = document.getElementById('wsr-range');
  const days = Math.max(1, Number(rangeEl?.value || 7));
  setWsrStatus('Loading data…');
  try {
    await _wsrEnsureProjectNameMap();
    const summary = await _wsrFetchSummary(days * 25);
    _wsrSetBusyMessage('Building report...');
    setWsrStatus('Building report…');
    const now = new Date();
    const reportWindow = _wsrGetReportWeekWindow(now);
    const thisStart = reportWindow.weekStart;
    const thisEnd = reportWindow.weekEnd;
    const prevEnd = thisStart;
    const prevStart = new Date(prevEnd.getTime() - 7 * 86400000);
    const md = buildWsrMarkdown(summary, { days: 7, windowStart: thisStart, windowEnd: thisEnd });
    const mdPrev = buildWsrMarkdown(summary, { days: 7, windowStart: prevStart, windowEnd: prevEnd, weekRef: new Date(prevEnd.getTime() - 1) });
    _wsrLastMarkdown = md;
    _wsrLastMarkdownPrev = mdPrev;
    _wsrSetTitle(thisEnd);
    _wsrSetPreviewText('this', md);
    _wsrSetPreviewText('prev', mdPrev);
    const prevLabel = document.getElementById('wsr-prev-label');
    if (prevLabel) {
      const wkP = _wsrIsoWeek(new Date(prevEnd.getTime() - 1));
      prevLabel.textContent = `Last week (Week ${wkP.week}, ${wkP.year})`;
    }
    const thisLabel = document.getElementById('wsr-this-label');
    if (thisLabel) {
      const wkT = _wsrIsoWeek(new Date(thisEnd.getTime() - 1));
      thisLabel.textContent = `This week (Week ${wkT.week}, ${wkT.year})`;
    }
    const stamp = now.toISOString();
    const genEl = document.getElementById('wsr-generated-at');
    if (genEl) genEl.textContent = stamp;
    _wsrSetBusyMessage('Saving history...');
    setWsrStatus('Saving history…');
    const currentMeta = _wsrBuildSnapshotMeta(thisStart, thisEnd, { stamp, days: 7, dataStatusVersion: 2 });
    _wsrSetActiveSnapshotMeta(currentMeta);
    _wsrWriteCachedReport({ md, mdPrev, stamp, days, dataStatusVersion: 2, windowStart: currentMeta.windowStart, windowEnd: currentMeta.windowEnd });
    appendWorkReportToHistory(_wsrBuildWeeklyHistoryEntries(summary, days, thisEnd, stamp));
    setWsrStatus('Ready.');
  } catch (e) {
    setWsrStatus('Failed: ' + (e?.message || e));
  } finally {
    _wsrGenerating = false;
    hideWsrBusy(true);
  }
}

function readWorkReportHistory() {
  try {
    const raw = localStorage.getItem(WSR_HISTORY_KEY);
    if (!raw) return [];
    const arr = JSON.parse(raw);
    return Array.isArray(arr) ? arr : [];
  } catch { return []; }
}

function writeWorkReportHistory(list) {
  try { localStorage.setItem(WSR_HISTORY_KEY, JSON.stringify(list.slice(0, WSR_HISTORY_MAX))); } catch {}
}

function _wsrHistoryKey(entry) {
  if (entry?.windowStart && entry?.windowEnd) return `${entry.windowStart}|${entry.windowEnd}`;
  return `${entry?.stamp || ''}|${entry?.days || ''}|${entry?.title || ''}`;
}

function _wsrFirstHeading(md) {
  const m = String(md || '').match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : '(untitled)';
}

function appendWorkReportToHistory(entry) {
  const incoming = (Array.isArray(entry) ? entry : [entry]).filter(e => e?.md);
  if (!incoming.length) return;
  const merged = new Map();
  readWorkReportHistory().forEach(e => merged.set(_wsrHistoryKey(e), e));
  incoming.forEach(e => {
    const wk = _wsrIsoWeek(e.stamp ? new Date(e.windowEnd || e.stamp) : new Date());
    const normalized = {
      ...e,
      title: e.title || `Week ${wk.week}, ${wk.year}`,
    };
    merged.set(_wsrHistoryKey(normalized), normalized);
  });
  const list = [...merged.values()].sort((a, b) => {
    const at = Date.parse(a?.windowEnd || a?.stamp || 0);
    const bt = Date.parse(b?.windowEnd || b?.stamp || 0);
    return bt - at;
  });
  writeWorkReportHistory(list);
  renderWorkReportHistory();
}

function _wsrHistoryWindowLabel(entry) {
  if (entry?.windowStart && entry?.windowEnd) {
    const end = new Date(entry.windowEnd);
    const endInclusive = Number.isFinite(end.getTime()) ? _wsrFormatWindowEndInclusive(end) : entry.windowEnd;
    return `${entry.windowStart} -> ${endInclusive}`;
  }
  return `${entry?.days ?? '—'}d`;
}

function _wsrWindowKey(windowStart, windowEnd) {
  return `${windowStart || ''}|${windowEnd || ''}`;
}

async function _wsrRefreshHistoryDataStatusFromApi(force = false) {
  const now = Date.now();
  if (!force && (now - _wsrHistoryStatusRefreshedAt) < 300000) return;
  const list = readWorkReportHistory();
  if (!list.length) return;
  try {
    const summary = await _wsrFetchSummary(5000);
    const events = summary?.activities || summary?.recent_events || summary?.events || [];
    const next = new Map();
    const refreshedList = list.map((e) => {
      if (!e?.windowStart || !e?.windowEnd) return e;
      const windowStart = new Date(e.windowStart);
      const windowEnd = new Date(e.windowEnd);
      const totalEvents = _wsrSummarizeEvents(events, windowStart.getTime(), windowEnd.getTime()).filtered.length;
      next.set(_wsrWindowKey(e.windowStart, e.windowEnd), totalEvents);
      return { ...e, totalEvents, dataStatusVersion: 2 };
    });
    writeWorkReportHistory(refreshedList);
    _wsrWindowEventCounts = next;
    _wsrHistoryStatusRefreshedAt = now;
    renderWorkReportHistory();
  } catch {}
}

function _wsrGetEntryTotalEvents(entry) {
  const key = _wsrWindowKey(entry?.windowStart, entry?.windowEnd);
  if (_wsrWindowEventCounts.has(key)) return _wsrWindowEventCounts.get(key);
  const direct = Number(entry?.totalEvents);
  if (Number.isFinite(direct) && direct >= 0 && Number(entry?.dataStatusVersion || 0) >= 2) return direct;
  return null;
}

function _wsrDataStatus(entry) {
  const totalEvents = _wsrGetEntryTotalEvents(entry);
  if (totalEvents === null) {
    return { label: 'Refresh needed', cls: 'pill pill-amber', title: 'This cached snapshot has not been checked against current CGA activity data yet.' };
  }
  if (totalEvents === 0) {
    return { label: 'Missing data', cls: 'pill pill-red', title: 'No activity events were found in this window.' };
  }
  return { label: `${totalEvents} events`, cls: 'pill pill-green', title: 'Activity exists for this window.' };
}

function _wsrSetPreviewLabels(currentEnd, prevEnd) {
  const prevLabel = document.getElementById('wsr-prev-label');
  if (prevLabel) {
    const wkP = _wsrIsoWeek(new Date(prevEnd.getTime() - 1));
    prevLabel.textContent = `Last week (Week ${wkP.week}, ${wkP.year})`;
  }
  const thisLabel = document.getElementById('wsr-this-label');
  if (thisLabel) {
    const wkT = _wsrIsoWeek(new Date(currentEnd.getTime() - 1));
    thisLabel.textContent = `This week (Week ${wkT.week}, ${wkT.year})`;
  }
}

function _wsrPreviewKind(which) {
  return which === 'prev' ? 'prev' : 'this';
}

function _wsrPreviewId(which) {
  return _wsrPreviewKind(which) === 'prev' ? 'wsr-preview-prev' : 'wsr-preview';
}

function _wsrSaveButtonId(which) {
  return _wsrPreviewKind(which) === 'prev' ? 'wsr-save-prev-btn' : 'wsr-save-btn';
}

function _wsrPreviewLabel(which) {
  return _wsrPreviewKind(which) === 'prev' ? 'Last week WSR' : 'This week WSR';
}

function _wsrGetPreviewText(which) {
  const el = document.getElementById(_wsrPreviewId(which));
  if (!el) return '';
  if (typeof el.value === 'string') return el.value;
  return el.innerText || el.textContent || '';
}

function _wsrSetPreviewText(which, markdown, clean = true) {
  const el = document.getElementById(_wsrPreviewId(which));
  if (!el) return;
  const text = String(markdown || '');
  if (typeof el.value === 'string') el.value = text;
  else el.textContent = text;
  if (clean) _wsrSetPreviewDirty(which, false);
}

function _wsrSetPreviewDirty(which, isDirty) {
  const kind = _wsrPreviewKind(which);
  const btn = document.getElementById(_wsrSaveButtonId(kind));
  const editor = document.getElementById(_wsrPreviewId(kind));
  if (btn) btn.disabled = !isDirty;
  if (editor) editor.classList.toggle('is-dirty', !!isDirty);
}

function markWorkReportDirty(which) {
  _wsrSetPreviewDirty(which, true);
  setWsrStatus(`${_wsrPreviewLabel(which)} has unsaved edits.`);
}

function handleWorkReportEditorKeydown(event, which) {
  if (!event || !(event.ctrlKey || event.metaKey) || String(event.key || '').toLowerCase() !== 's') return;
  event.preventDefault();
  saveWorkReportEdit(which);
}

function _wsrBuildSnapshotMeta(windowStart, windowEnd, extra = {}) {
  const start = new Date(windowStart);
  const end = new Date(windowEnd);
  const meta = { ...extra };
  if (Number.isFinite(start.getTime()) && Number.isFinite(end.getTime())) {
    meta.windowStart = _wsrFormatDate(start);
    meta.windowEnd = _wsrFormatDate(end);
    meta.prevWindowEnd = meta.windowStart;
    meta.prevWindowStart = _wsrFormatDate(new Date(start.getTime() - 7 * 86400000));
  }
  return meta;
}

function _wsrSetActiveSnapshotMeta(meta = {}) {
  _wsrActiveSnapshot = { ...meta };
}

function _wsrReadCachedReport() {
  try {
    const raw = localStorage.getItem(WSR_STORAGE_KEY);
    const parsed = raw ? JSON.parse(raw) : {};
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {};
  } catch { return {}; }
}

function _wsrWriteCachedReport(patch) {
  const next = { ..._wsrReadCachedReport(), ...patch };
  try { localStorage.setItem(WSR_STORAGE_KEY, JSON.stringify(next)); } catch {}
  return next;
}

function _wsrFindHistoryEntry(windowStart, windowEnd) {
  const key = _wsrWindowKey(windowStart, windowEnd);
  return readWorkReportHistory().find(entry => _wsrWindowKey(entry?.windowStart, entry?.windowEnd) === key) || null;
}

function saveWorkReportEdit(which = 'this') {
  const kind = _wsrPreviewKind(which);
  _wsrLastMarkdown = _wsrGetPreviewText('this');
  _wsrLastMarkdownPrev = _wsrGetPreviewText('prev');
  const savedAt = new Date().toISOString();
  const active = _wsrActiveSnapshot || {};
  const cached = _wsrReadCachedReport();
  const cachePatch = {
    md: _wsrLastMarkdown,
    mdPrev: _wsrLastMarkdownPrev,
    stamp: savedAt,
    editedAt: savedAt,
    days: active.days || cached.days || 7,
    dataStatusVersion: active.dataStatusVersion || cached.dataStatusVersion || 2,
  };
  if (active.windowStart && active.windowEnd) {
    cachePatch.windowStart = active.windowStart;
    cachePatch.windowEnd = active.windowEnd;
  }
  _wsrWriteCachedReport(cachePatch);

  const historyUpdates = [];
  if (active.windowStart && active.windowEnd) {
    historyUpdates.push({
      ...active,
      ...cachePatch,
      title: active.title,
      totalEvents: active.totalEvents,
    });
  }
  if (kind === 'prev' && active.prevWindowStart && active.prevWindowEnd) {
    const existingPrev = _wsrFindHistoryEntry(active.prevWindowStart, active.prevWindowEnd) || {};
    historyUpdates.push({
      ...existingPrev,
      md: _wsrLastMarkdownPrev,
      mdPrev: existingPrev.mdPrev || '',
      stamp: savedAt,
      editedAt: savedAt,
      days: existingPrev.days || 7,
      windowStart: active.prevWindowStart,
      windowEnd: active.prevWindowEnd,
      dataStatusVersion: existingPrev.dataStatusVersion || active.dataStatusVersion || 2,
    });
  }
  if (historyUpdates.length) appendWorkReportToHistory(historyUpdates);
  else renderWorkReportHistory();

  _wsrSetActiveSnapshotMeta({ ...active, ...cachePatch });
  _wsrSetPreviewDirty(kind, false);
  const stampEl = document.getElementById('wsr-generated-at');
  if (stampEl) stampEl.textContent = savedAt;
  setWsrStatus(`${_wsrPreviewLabel(kind)} saved.`);
  toast(`${_wsrPreviewLabel(kind)} saved`);
}

function _wsrResetHistoryPagination() {
  _wsrHistoryVisibleCount = WSR_HISTORY_BATCH_SIZE;
}

function loadMoreWorkReportHistory() {
  const total = readWorkReportHistory().length;
  _wsrHistoryVisibleCount = Math.min(total, _wsrHistoryVisibleCount + WSR_HISTORY_BATCH_SIZE);
  renderWorkReportHistory();
}

function renderWorkReportHistory() {
  const tbody = document.getElementById('wsr-history-body');
  const countEl = document.getElementById('wsr-history-count');
  const loadMoreBtn = document.getElementById('wsr-history-load-more-btn');
  if (!tbody) return;
  const list = readWorkReportHistory();
  const visible = list.slice(0, Math.max(0, _wsrHistoryVisibleCount));
  if (countEl) countEl.textContent = `${list.length} entr${list.length === 1 ? 'y' : 'ies'}`;
  if (!list.length) {
    tbody.innerHTML = `<tr><td colspan="5"><div class="empty-state">No reports stored yet.</div></td></tr>`;
    if (loadMoreBtn) loadMoreBtn.hidden = true;
    return;
  }
  tbody.innerHTML = visible.map((e, idx) => {
    const stamp = esc(e.stamp || '');
    const wk = e.windowEnd ? _wsrIsoWeek(new Date(e.windowEnd)) : (e.stamp ? _wsrIsoWeek(new Date(e.stamp)) : null);
    const weekLabel = wk ? `Week ${wk.week}, ${wk.year}` : (e.title || _wsrFirstHeading(e.md));
    const title = esc(weekLabel);
    const windowLabel = esc(_wsrHistoryWindowLabel(e));
    const dataStatus = _wsrDataStatus(e);
    return `<tr>
      <td>${title}</td>
      <td class="mono" style="text-align:center">${stamp}</td>
      <td class="mono" style="text-align:center">${windowLabel}</td>
      <td style="text-align:center"><span class="${dataStatus.cls}" title="${esc(dataStatus.title)}">${esc(dataStatus.label)}</span></td>
      <td class="actions-col">
        <button class="btn btn-sm" onclick="viewWorkReportFromHistory(${idx})">View</button>
        <button class="btn btn-sm" onclick="regenerateWorkReportFromHistory(${idx})" title="Re-run WSR for the same window length">Regenerate</button>
        <button class="btn btn-sm" onclick="copyWorkReportFromHistory(${idx})">Copy</button>
        <button class="btn btn-sm btn-danger" onclick="deleteWorkReportFromHistory(${idx})">Delete</button>
      </td>
    </tr>`;
  }).join('');

  if (loadMoreBtn) {
    const remaining = Math.max(0, list.length - visible.length);
    const loadNext = Math.min(WSR_HISTORY_BATCH_SIZE, remaining);
    loadMoreBtn.hidden = remaining <= 0;
    loadMoreBtn.disabled = remaining <= 0;
    loadMoreBtn.textContent = remaining > 0
      ? `Load ${loadNext} more (${visible.length}/${list.length})`
      : `All ${list.length} loaded`;
  }
}

function viewWorkReportFromHistory(idx) {
  const list = readWorkReportHistory();
  const e = list[idx];
  if (!e) return;
  _wsrLastMarkdown = e.md;
  _wsrLastMarkdownPrev = e.mdPrev || '';
  if (e.windowEnd) _wsrSetTitle(new Date(e.windowEnd));
  _wsrSetPreviewText('this', e.md);
  _wsrSetPreviewText('prev', e.mdPrev || '_(no previous-week snapshot stored)_');
  if (e.windowEnd) {
    const currentEnd = new Date(e.windowEnd);
    const prevEnd = e.windowStart ? new Date(e.windowStart) : new Date(currentEnd.getTime() - 7 * 86400000);
    _wsrSetPreviewLabels(currentEnd, prevEnd);
    _wsrSetActiveSnapshotMeta(_wsrBuildSnapshotMeta(prevEnd, currentEnd, { ...e }));
  } else {
    _wsrSetActiveSnapshotMeta({ ...e });
  }
  const stampEl = document.getElementById('wsr-generated-at');
  if (stampEl) stampEl.textContent = e.stamp || '—';
  setWsrStatus('Viewing snapshot from ' + (e.stamp || 'history') + '.');
  try { window.scrollTo({ top: 0, behavior: 'smooth' }); } catch {}
}

async function copyWorkReportFromHistory(idx) {
  const list = readWorkReportHistory();
  const e = list[idx];
  if (!e?.md) return;
  try {
    await navigator.clipboard.writeText(e.md);
    toast('WSR snapshot copied');
  } catch (err) {
    toast('Copy failed: ' + (err?.message || err), 'error');
  }
}

async function regenerateWorkReportFromHistory(idx) {
  const list = readWorkReportHistory();
  const e = list[idx];
  if (!e) return;
  if (!e.windowStart || !e.windowEnd) {
    await generateWorkReport();
    return;
  }
  showWsrBusy('Regenerating...');
  setWsrStatus('Generating…');
  try {
    await _wsrEnsureProjectNameMap();
    const days = Math.max(1, Number(e.days || 7));
    const summary = await _wsrFetchSummary(days * 25);
    const windowStart = new Date(e.windowStart);
    const windowEnd = new Date(e.windowEnd);
    const totalEvents = _wsrSummarizeEvents(summary?.activities || summary?.recent_events || summary?.events || [], windowStart.getTime(), windowEnd.getTime()).filtered.length;
    const prevEnd = new Date(windowStart);
    const prevStart = new Date(prevEnd.getTime() - 7 * 86400000);
    const refreshed = {
      ...e,
      md: buildWsrMarkdown(summary, { days, windowStart, windowEnd, weekRef: new Date(windowEnd.getTime() - 1) }),
      mdPrev: buildWsrMarkdown(summary, { days: 7, windowStart: prevStart, windowEnd: prevEnd, weekRef: new Date(prevEnd.getTime() - 1) }),
      stamp: new Date().toISOString(),
      totalEvents,
      dataStatusVersion: 2,
    };
    appendWorkReportToHistory(refreshed);
    viewWorkReportFromHistory(readWorkReportHistory().findIndex(item => _wsrHistoryKey(item) === _wsrHistoryKey(refreshed)));
    setWsrStatus('Ready.');
  } catch (err) {
    setWsrStatus('Failed: ' + (err?.message || err));
  } finally {
    hideWsrBusy(true);
  }
}

function deleteWorkReportFromHistory(idx) {
  const list = readWorkReportHistory();
  if (!list[idx]) return;
  if (!confirm('Delete this WSR snapshot?')) return;
  list.splice(idx, 1);
  writeWorkReportHistory(list);
  renderWorkReportHistory();
}

function clearWorkReportHistory() {
  if (!confirm('Delete ALL stored WSR snapshots? This cannot be undone.')) return;
  try { localStorage.removeItem(WSR_HISTORY_KEY); } catch {}
  _wsrResetHistoryPagination();
  renderWorkReportHistory();
}

async function regenerateAllWorkReports() {
  const list = readWorkReportHistory();
  if (!list.length) {
    toast('No history to regenerate');
    return;
  }
  if (!confirm(`Regenerate all ${list.length} stored WSR snapshots?`)) return;
  showWsrBusy('Regenerating all...');
  setWsrStatus('Regenerating all snapshots…');
  try {
    await _wsrEnsureProjectNameMap();
    const summary = await _wsrFetchSummary(5000);
    const events = summary?.activities || summary?.recent_events || summary?.events || [];
    const refreshedList = list.map((e) => {
      if (!e?.windowStart || !e?.windowEnd) return e;
      const windowStart = new Date(e.windowStart);
      const windowEnd = new Date(e.windowEnd);
      const days = Math.max(1, Number(e.days || Math.ceil((windowEnd.getTime() - windowStart.getTime()) / 86400000) || 7));
      const totalEvents = _wsrSummarizeEvents(events, windowStart.getTime(), windowEnd.getTime()).filtered.length;
      const prevEnd = new Date(windowStart);
      const prevStart = new Date(prevEnd.getTime() - 7 * 86400000);
      return {
        ...e,
        days,
        md: buildWsrMarkdown(summary, { days, windowStart, windowEnd, weekRef: new Date(windowEnd.getTime() - 1) }),
        mdPrev: buildWsrMarkdown(summary, { days: 7, windowStart: prevStart, windowEnd: prevEnd, weekRef: new Date(prevEnd.getTime() - 1) }),
        stamp: new Date().toISOString(),
        totalEvents,
        dataStatusVersion: 2,
      };
    });
    writeWorkReportHistory(refreshedList);
    _wsrResetHistoryPagination();
    renderWorkReportHistory();
    viewWorkReportFromHistory(0);
    setWsrStatus('Ready.');
    toast(`Regenerated ${refreshedList.length} snapshots`);
  } catch (err) {
    setWsrStatus('Failed: ' + (err?.message || err));
    toast('Regenerate all failed: ' + (err?.message || err), 'error');
  } finally {
    hideWsrBusy(true);
  }
}

async function copyWorkReport() {
  if (!_wsrLastMarkdown) { await generateWorkReport(); }
  _wsrLastMarkdown = _wsrGetPreviewText('this') || _wsrLastMarkdown;
  try {
    await navigator.clipboard.writeText(_wsrLastMarkdown || '');
    toast('This week WSR copied');
  } catch (e) {
    toast('Copy failed: ' + (e?.message || e), 'error');
  }
}

async function copyWorkReportPrev() {
  if (!_wsrLastMarkdownPrev) { await generateWorkReport(); }
  _wsrLastMarkdownPrev = _wsrGetPreviewText('prev') || _wsrLastMarkdownPrev;
  try {
    await navigator.clipboard.writeText(_wsrLastMarkdownPrev || '');
    toast('Last week WSR copied');
  } catch (e) {
    toast('Copy failed: ' + (e?.message || e), 'error');
  }
}

function updateWsrAutoSchedule() {
  const sel = document.getElementById('wsr-auto');
  const interval = Math.max(0, Number(sel?.value || 0));
  if (_wsrAutoTimer) { clearInterval(_wsrAutoTimer); _wsrAutoTimer = null; }
  if (interval > 0) {
    _wsrAutoTimer = setInterval(() => { generateWorkReport(); }, interval);
  }
}

function loadReportsPlugin() {
  try {
    const preferences = readReportPreferences();
    const auto = document.getElementById('wsr-auto');
    if (auto) auto.value = preferences.auto_interval;
  } catch (error) {
    toast('Report preferences could not be loaded: ' + error.message, 'error');
  }
  if (!_wsrGenerating) hideWsrBusy(true);
  // Populate the template textarea (from storage or default) on every entry.
  initReportsTemplateEditor();
  const reportWindow = _wsrGetReportWeekWindow(new Date());
  _wsrSetTitle(reportWindow.weekEnd);
  _wsrSetPreviewLabels(reportWindow.weekEnd, reportWindow.weekStart);
  _wsrSetActiveSnapshotMeta(_wsrBuildSnapshotMeta(reportWindow.weekStart, reportWindow.weekEnd, { days: 7, dataStatusVersion: 2 }));
  _wsrResetHistoryPagination();
  renderWorkReportHistory();
  // Restore last cached report so the tab is not blank.
  if (!_wsrLastMarkdown) {
    try {
      const cached = _wsrReadCachedReport();
      if (cached?.md) {
        _wsrLastMarkdown = cached.md;
        _wsrLastMarkdownPrev = cached.mdPrev || '';
        _wsrSetPreviewText('this', cached.md);
        if (cached.mdPrev) _wsrSetPreviewText('prev', cached.mdPrev);
        const stampEl = document.getElementById('wsr-generated-at');
        if (stampEl) stampEl.textContent = cached.stamp || '—';
        if (cached.windowStart && cached.windowEnd) {
          _wsrSetActiveSnapshotMeta(_wsrBuildSnapshotMeta(cached.windowStart, cached.windowEnd, { ...cached }));
        }
      }
    } catch {}
  }
  updateWsrAutoSchedule();
  _wsrRefreshHistoryDataStatusFromApi();
  if (!_wsrAutoGeneratedOnce && !_wsrLastMarkdown) {
    _wsrAutoGeneratedOnce = true;
    generateWorkReport();
  }
}
