function _wsrCompactText(value, maxLen = 260) {
  const entityMap = { nbsp: ' ', amp: '&', lt: '<', gt: '>' };
  const text = String(value || '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(nbsp|amp|lt|gt);/gi, (_, entity) => entityMap[entity.toLowerCase()] || '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) return '';
  return text.length > maxLen ? `${text.slice(0, Math.max(0, maxLen - 3)).trimEnd()}...` : text;
}

function _wsrNormalizeText(value) {
  return _wsrCompactText(value, 1000).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

function _wsrIsSimilarText(a, b) {
  const left = _wsrNormalizeText(a);
  const right = _wsrNormalizeText(b);
  if (!left || !right) return false;
  return left === right || left.includes(right) || right.includes(left);
}

function _wsrAddDetailLine(lines, seen, label, value, maxLen = 260) {
  const text = _wsrCompactText(value, maxLen);
  if (!text) return;
  const key = _wsrNormalizeText(text);
  if (!key || seen.has(key)) return;
  seen.add(key);
  lines.push(`${label}: ${text}`);
}

function _wsrWorkRefLabel(activity) {
  const metadata = _wsrMetadata(activity);
  if (_wsrExternalRefs(activity).length) return true;
  const text = [
    activity?.event_type,
    activity?.title,
    activity?.summary,
    activity?.body_text,
    activity?.source_item_id,
    activity?.source_url,
    JSON.stringify(metadata),
  ].join(' ');
  return /\b(ado|pbi|pr|pull request|work item|workitems|_workitems)\b/i.test(text) || /\b\d{7,}\b/.test(text);
}

function _wsrAdoDetailLine(activity) {
  const metadata = _wsrMetadata(activity);
  const resolved = _wsrExternalRefs(activity).find(ref => ref?.provider === 'azure_devops' && ref?.type === 'work_item' && ref?.status === 'ok');
  if (resolved) {
    const pieces = [];
    const label = `${resolved.work_item_type || 'ADO item'} ${resolved.id || ''}`.trim();
    if (label) pieces.push(label);
    if (resolved.title) pieces.push(_wsrCompactText(resolved.title, 180));
    if (resolved.state) pieces.push(`state ${resolved.state}`);
    if (resolved.assigned_to) pieces.push(`owner ${resolved.assigned_to}`);
    if (resolved.iteration_path) pieces.push(`iteration ${resolved.iteration_path}`);
    return pieces.join('; ');
  }
  const ado = metadata.ado && typeof metadata.ado === 'object' ? metadata.ado : metadata;
  const adoId = ado.ado_id || ado.pbi_id || metadata.ado_id || metadata.pbi_id || '';
  const adoType = ado.ado_type || ado.work_item_type || metadata.ado_type || metadata.work_item_type || '';
  const adoState = ado.ado_state || ado.state || metadata.ado_state || metadata.state || '';
  const pieces = [];
  if (adoType || adoId) pieces.push(`${adoType || 'ADO item'}${adoId ? ` ${adoId}` : ''}`);
  if (adoState) pieces.push(`state ${adoState}`);
  if (ado.ado_iteration_path || metadata.ado_iteration_path) pieces.push(`iteration ${ado.ado_iteration_path || metadata.ado_iteration_path}`);
  if (ado.ado_area_path || metadata.ado_area_path) pieces.push(`area ${ado.ado_area_path || metadata.ado_area_path}`);
  if (ado.ado_changed_date || metadata.ado_changed_date) pieces.push(`changed ${ado.ado_changed_date || metadata.ado_changed_date}`);
  return pieces.join('; ');
}

function _wsrPrDetailLines(activity) {
  const metadata = _wsrMetadata(activity);
  const lines = [];
  _wsrExternalRefs(activity)
    .filter(ref => ref?.provider === 'azure_devops' && ref?.type === 'pull_request')
    .slice(0, 3)
    .forEach(ref => {
      const id = ref.id || '';
      const title = _wsrCompactText(ref.title || '', 180);
      const status = ref.state ? ` (${ref.state})` : '';
      const detail = ref.status === 'ok'
        ? `ADO PR${id ? ` ${id}` : ''}${status}${title ? `: ${title}` : ''}`
        : `ADO PR${id ? ` ${id}` : ''}: ${ref.status || 'not resolved'}`;
      lines.push(detail);
    });
  const pullRequests = Array.isArray(metadata.pull_requests) ? metadata.pull_requests : [];
  pullRequests.slice(0, 3).forEach(pr => {
    const id = pr.id || pr.number || pr.pullRequestId || '';
    const title = _wsrCompactText(pr.title || pr.name || '', 180);
    const status = pr.status ? ` (${pr.status})` : '';
    if (id || title) lines.push(`ADO PR${id ? ` ${id}` : ''}${status}${title ? `: ${title}` : ''}`);
  });
  if (metadata.pr && typeof metadata.pr === 'object') {
    const pr = metadata.pr;
    const id = pr.number || pr.id || pr.pullRequestId || '';
    const branch = pr.branch ? ` branch ${pr.branch}` : '';
    const commit = pr.commit ? ` commit ${pr.commit}` : '';
    if (id || branch || commit) lines.push(`PR${id ? ` #${id}` : ''}:${branch}${commit}`.replace(/:\s*$/, ''));
  }
  if (Array.isArray(metadata.prs) && metadata.prs.length) {
    lines.push(`Related PRs: ${metadata.prs.slice(0, 8).map(pr => `#${pr}`).join(', ')}`);
  }
  if (Array.isArray(metadata.inferred_pbis) && metadata.inferred_pbis.length) {
    lines.push(`Related PBIs: ${metadata.inferred_pbis.slice(0, 8).join(', ')}`);
  }
  if (metadata.pbi_id) lines.push(`PBI: ${metadata.pbi_id}`);
  return lines;
}

function _wsrActivityDetailLines(activity, title) {
  const lines = [];
  const seen = new Set();
  const summary = _wsrCompactText(activity?.summary, 320);
  const bodyText = _wsrCompactText(activity?.body_text || activity?.description, 360);
  if (summary && !_wsrIsSimilarText(summary, title)) _wsrAddDetailLine(lines, seen, 'Details', summary, 320);
  if (bodyText && !_wsrIsSimilarText(bodyText, title) && !_wsrIsSimilarText(bodyText, summary)) _wsrAddDetailLine(lines, seen, 'Evidence', bodyText, 360);
  const adoDetail = _wsrAdoDetailLine(activity);
  _wsrAddDetailLine(lines, seen, 'ADO', adoDetail, 320);
  _wsrPrDetailLines(activity).forEach(line => _wsrAddDetailLine(lines, seen, 'Linkage', line, 260));
  if (activity?.source_url) _wsrAddDetailLine(lines, seen, 'Source', activity.source_url, 260);
  return lines;
}

function _wsrFormatHighlight(activity) {
  const proj = _wsrProjectDisplayName(activity);
  const title = _wsrCompactText(activity?.title || activity?.summary || activity?.event_type || 'activity', 220);
  const lines = [`- [${proj}] ${title}`];
  if (_wsrWorkRefLabel(activity)) {
    _wsrActivityDetailLines(activity, title).forEach(line => lines.push(`  - ${line}`));
  }
  return lines.join('\n');
}

