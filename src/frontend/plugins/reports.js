function _wsrMapToBullets(map) {
  const entries = [...map.entries()].sort((a, b) => b[1] - a[1]);
  if (!entries.length) return '- _(none)_';
  return entries.map(([k, v]) => `- **${k}** — ${v}`).join('\n');
}

function _wsrProjectEntries(map) {
  return [...map.entries()].sort((a, b) => (b[1] - a[1]) || String(a[0]).localeCompare(String(b[0])));
}

function _wsrProjectNamesText(map) {
  const names = _wsrProjectEntries(map).map(([name]) => String(name || '').trim()).filter(Boolean);
  return names.length ? names.join(', ') : '(none)';
}

function _wsrProjectTagsText(map) {
  const tags = _wsrProjectEntries(map).map(([name]) => {
    const slug = String(name || 'unscoped')
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
    return `#${slug || 'unscoped'}`;
  });
  return tags.length ? tags.join(' ') : '(none)';
}

