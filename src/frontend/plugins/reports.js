function _wsrFormatDate(d) {
  return d.toISOString().slice(0, 10);
}

function _wsrFormatWindowEndInclusive(endExclusive) {
  const t = new Date(endExclusive);
  if (!Number.isFinite(t.getTime())) return _wsrFormatDate(new Date());
  return _wsrFormatDate(new Date(t.getTime() - 86400000));
}

function _wsrStartOfDay(d) {
  const t = new Date(d);
  t.setHours(0, 0, 0, 0);
  return t;
}

function _wsrStartOfThuWeek(d) {
  const t = _wsrStartOfDay(d);
  const day = t.getDay(); // 0=Sun ... 4=Thu
  const delta = (day - 4 + 7) % 7;
  t.setDate(t.getDate() - delta);
  return t;
}

function _wsrGetReportWeekWindow(anchor) {
  const weekStart = _wsrStartOfThuWeek(anchor || new Date()); // Thu 00:00
  const weekEnd = new Date(weekStart.getTime() + 7 * 86400000); // Next Thu 00:00, displayed as Wed
  return { weekStart, weekEnd };
}

function _wsrGetEventTimeValue(event) {
  return event?.occurred_at || event?.created_at || event?.timestamp || event?.ts || event?.synced_at || 0;
}

function _wsrSummarizeEvents(events, startMs, endMs) {
  const filtered = (Array.isArray(events) ? events : []).filter(e => {
    const t = Date.parse(_wsrGetEventTimeValue(e));
    if (!Number.isFinite(t)) return false;
    return t >= startMs && t < endMs;
  });
  const byProject = new Map();
  const byType = new Map();
  const byStatus = new Map();
  filtered.forEach(e => {
    const proj = _wsrProjectDisplayName(e);
    const type = e.event_type || e.kind || 'event';
    const status = e.status || e.state || '';
    byProject.set(proj, (byProject.get(proj) || 0) + 1);
    byType.set(type, (byType.get(type) || 0) + 1);
    if (status) byStatus.set(status, (byStatus.get(status) || 0) + 1);
  });
  return { filtered, byProject, byType, byStatus };
}

